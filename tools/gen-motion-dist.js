/* Builds motion-library/dist/ - the standalone bundle.

   One file, no imports, no build step at the other end: the tokens and every
   animation concatenated in load order, so the bundle can be dropped into a
   project that has none of the rest of the hub. Generated, never hand-edited.

   Regenerate with:  node tools/gen-motion-dist.js */
var fs = require("fs"), path = require("path");
var R = path.join(__dirname, "..");
var ML = path.join(R, "motion-library");
var DIST = path.join(ML, "dist");

var tokens = fs.readFileSync(path.join(ML, "tokens", "motion-tokens.css"), "utf8");
var base = fs.readFileSync(path.join(ML, "base", "base-animations.css"), "utf8");
var lib = JSON.parse(fs.readFileSync(path.join(ML, "library.json"), "utf8"));

/* the bundle must not depend on anything the hub happens to define */
["@import", "url("].forEach(function (bad) {
  if (tokens.indexOf(bad) > -1 || base.indexOf(bad) > -1) {
    console.error("Source CSS contains " + bad + " - the bundle would not be self-contained");
    process.exit(1);
  }
});

var stamp = new Date().toISOString().slice(0, 10);
var header =
  "/*! Continia Motion — " + lib.length + " animations on one set of tokens\n" +
  " *  Built " + stamp + " from motion-library/tokens/ + motion-library/base/.\n" +
  " *  GENERATED by tools/gen-motion-dist.js — do not edit this file; edit\n" +
  " *  motion-library/base/base-animations.css and regenerate.\n" +
  " *\n" +
  " *  <link rel=\"stylesheet\" href=\"continia-motion.css\">\n" +
  " *  <div class=\"ml-fade-up\">…</div>            default speed\n" +
  " *  <div class=\"ml-fade-up ml-slower\">…</div>  2× slower\n" +
  " *\n" +
  " *  Continia internal. The catalogue covers the motion ideas found in\n" +
  " *  Animate.css and Animista; no code from either is used here.\n" +
  " */\n";

var bundle = header + "\n" +
  "/* ===================== 1. tokens ===================== */\n" + tokens.trim() + "\n\n" +
  "/* ===================== 2. animations ================= */\n" + base.trim() + "\n";

/* Conservative minifier: comments out, whitespace collapsed, padding removed
   around the four characters where it can never carry meaning. ":" is left
   alone on purpose - "a :hover" and "a:hover" are different selectors, and a
   minifier that cannot tell them apart has no business touching either. */
function mini(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{};,])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}
var banner = "/*! Continia Motion " + lib.length + " animations · built " + stamp +
  " · generated by tools/gen-motion-dist.js */\n";
var minified = banner + mini(bundle) + "\n";

/* ---------- README ---------- */
var CATS = [
  ["entrance", "Entrances", "Something arriving. They decelerate — the easing is expo-out."],
  ["exit", "Exits", "Something leaving. Shorter than the entrances and they accelerate away; a slow exit reads as a mistake."],
  ["attention", "Attention", "One shot, then back to rest. Never loop these — a repeating alert stops being an alert."],
  ["text", "Text", "These animate letter-spacing, which the browser cannot composite on the GPU. One line at a time, never a paragraph."],
  ["ambient", "Ambient", "Loops. They run until something stops them, so one per screen."]
];
var rows = CATS.map(function (c) {
  var es = lib.filter(function (e) { return e.category === c[0]; });
  return "### " + c[1] + " (" + es.length + ")\n\n" + c[2] + "\n\n" +
    "| Class | What it does |\n|---|---|\n" +
    es.map(function (e) { return "| `ml-" + e.slug + "` | " + e.blurb + " |"; }).join("\n") + "\n";
}).join("\n");

var tokenRows = (tokens.match(/^\s*(--motion-[a-z-]+):\s*([^;]+);/gm) || []).map(function (l) {
  var m = l.match(/(--motion-[a-z-]+):\s*([^;]+);/);
  return "| `" + m[1] + "` | `" + m[2].trim() + "` |";
}).join("\n");

var readme = "# Continia Motion\n\n" +
  lib.length + " animations built on one set of tokens. Vanilla CSS — no framework, no build step, " +
  "no JavaScript required. Drop the file in and put a class on an element.\n\n" +
  "```html\n<link rel=\"stylesheet\" href=\"continia-motion.css\">\n\n" +
  "<div class=\"ml-fade-up\">Automate your AP in Business Central</div>\n```\n\n" +
  "`continia-motion.min.css` is the same file with comments and whitespace removed.\n\n" +
  "## Speed\n\n" +
  "Four classes scale whatever duration an animation already has, so one class slows an entrance, " +
  "an exit and a loop by the same factor:\n\n" +
  "| Class | Factor |\n|---|---|\n| `ml-fast` | 0.75× |\n| `ml-slow` | 1.5× |\n" +
  "| `ml-slower` | 2× |\n| `ml-slowest` | 3× |\n\n" +
  "They set `--ml-scale`, which is an inherited custom property — put the class on a wrapper and " +
  "everything inside it runs at that speed:\n\n" +
  "```html\n<section class=\"ml-slower\">\n  <h2 class=\"ml-fade-up\">…</h2>\n  <p class=\"ml-fade-up\">…</p>\n</section>\n```\n\n" +
  "**Do not slow something down by editing a token.** The tokens are the timing scale the whole " +
  "set is built on; changing one there moves every animation that uses it.\n\n" +
  "## Stagger\n\n" +
  "`--ml-index` multiplies the stagger token, so a list builds itself:\n\n" +
  "```html\n<ul>\n  <li class=\"ml-fade-up\" style=\"--ml-index: 0\">Document Capture</li>\n" +
  "  <li class=\"ml-fade-up\" style=\"--ml-index: 1\">Expense Management</li>\n" +
  "  <li class=\"ml-fade-up\" style=\"--ml-index: 2\">Continia Banking</li>\n</ul>\n```\n\n" +
  "## Playing on scroll\n\n" +
  "Add `ml-paused` and take it off when the element comes into view. This is the only place the " +
  "bundle needs JavaScript, and it is optional:\n\n" +
  "```html\n<div class=\"ml-fade-up ml-paused\">…</div>\n```\n\n" +
  "```js\nvar io = new IntersectionObserver(function (entries) {\n" +
  "  entries.forEach(function (e) {\n" +
  "    if (!e.isIntersecting) return;\n" +
  "    e.target.classList.remove(\"ml-paused\");\n" +
  "    io.unobserve(e.target);\n" +
  "  });\n}, { threshold: 0.3 });\n\n" +
  "document.querySelectorAll(\".ml-paused\").forEach(function (el) { io.observe(el); });\n```\n\n" +
  "## Reduced motion\n\n" +
  "Handled in the file. Under `prefers-reduced-motion: reduce` the durations and travel distances " +
  "collapse, every loop switches off, and the animations that rotate, skew or flip in 3D are " +
  "swapped for a plain fade — those cannot be made safe by shortening them. Nothing disappears: " +
  "every element still ends in its final state.\n\n" +
  "To preview both versions without changing the OS setting, set `data-motion` on `<html>`:\n\n" +
  "```html\n<html data-motion=\"reduced\">   <!-- or \"full\" to override the OS setting -->\n```\n\n" +
  "## The catalogue\n\n" + rows + "\n" +
  "## Overrides\n\n" +
  "Per element, without touching the bundle:\n\n" +
  "| Property | Does |\n|---|---|\n" +
  "| `--ml-duration` | Replaces the animation's duration |\n" +
  "| `--ml-ease` | Replaces its easing |\n" +
  "| `--ml-scale` | Multiplies the duration (what the speed classes set) |\n" +
  "| `--ml-index` | Stagger position |\n" +
  "| `--ml-stagger` | Stagger step |\n\n" +
  "## Tokens\n\n" +
  "| Token | Value |\n|---|---|\n" + tokenRows + "\n\n" +
  "## Provenance\n\n" +
  "Continia internal. The catalogue covers the motion ideas you find in Animate.css and Animista, " +
  "but no code from either is used: their keyframes carry per-animation constants, and every " +
  "animation here has to come off the duration scale above. That is the whole reason the timings " +
  "differ from theirs.\n\n" +
  "Generated from `motion-library/base/base-animations.css` by `tools/gen-motion-dist.js`. " +
  "Edit the source and regenerate — never edit `dist/`.\n";

fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(path.join(DIST, "continia-motion.css"), bundle);
fs.writeFileSync(path.join(DIST, "continia-motion.min.css"), minified);
fs.writeFileSync(path.join(DIST, "README.md"), readme);

function kb(s) { return (Buffer.byteLength(s) / 1024).toFixed(1) + " KB"; }
console.log("dist/continia-motion.css      " + kb(bundle));
console.log("dist/continia-motion.min.css  " + kb(minified) +
  "  (" + Math.round(100 - Buffer.byteLength(minified) / Buffer.byteLength(bundle) * 100) + "% smaller)");
console.log("dist/README.md                " + kb(readme));
